const LanguageContext = createContext(null);

const stripEmoji = (text) => text
  .replace(/[\p{Extended_Pictographic}\uFE0F\u200D]/gu, '')
  .replace(/[ \t]{2,}/g, ' ')
  .replace(/[ \t]+([,.;!?])/g, '$1')
  .trim();

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    return localStorage.getItem('cafe_lang') || 'es-MX';
  });

  const setLanguage = (langCode) => {
    localStorage.setItem('cafe_lang', langCode);
    setLanguageState(langCode);
  };

  const t = (key) => {
    const langDict = TRANSLATIONS[language] || TRANSLATIONS['es-MX'];
    const text = langDict[key] || TRANSLATIONS['es-MX']?.[key] || key;
    return stripEmoji(text);
  };

  const currentLangMeta = LANGUAGES.find(l => l.code === language) || LANGUAGES[0];

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, currentLangMeta, LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useLanguage = () => {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    return {
      language: 'es-MX',
      setLanguage: () => {},
      t: (k) => k,
      currentLangMeta: LANGUAGES[0],
      LANGUAGES
    };
  }
  return ctx;
};
